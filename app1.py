def get_settings(user_id):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT maintenance_calories, body_weight_kg FROM user_settings WHERE user_id=%s",
                (user_id,),
            )
            row = cur.fetchone()
    if row:
        return float(row["maintenance_calories"]), float(row["body_weight_kg"])
    return 2000.0, 70.0


def save_settings(user_id, maintenance, weight_kg):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO user_settings(user_id, maintenance_calories, body_weight_kg)
                VALUES (%s, %s, %s)
                ON CONFLICT(user_id) DO UPDATE
                SET maintenance_calories=EXCLUDED.maintenance_calories,
                    body_weight_kg=EXCLUDED.body_weight_kg
            """, (user_id, float(maintenance), float(weight_kg)))


def add_exercise(user_id, activity, minutes, calories_burned, day):
    now = datetime.now(TIMEZONE).isoformat(timespec="seconds")
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO exercise_entries
                (user_id, activity, minutes, calories_burned, entry_date, created_at)
                VALUES (%s, %s, %s, %s, %s, %s)
            """, (user_id, activity, float(minutes), float(calories_burned), day.isoformat(), now))


def get_exercises(user_id, day):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT id, activity, minutes, calories_burned FROM exercise_entries
                WHERE user_id=%s AND entry_date=%s ORDER BY id DESC
            """, (user_id, day.isoformat()))
            return [dict(r) for r in cur.fetchall()]


def delete_exercise(user_id, entry_id):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("DELETE FROM exercise_entries WHERE id=%s AND user_id=%s", (entry_id, user_id))


def get_saved_intake(user_id, day):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT calories FROM daily_intake WHERE user_id=%s AND day=%s", (user_id, day.isoformat()))
            row = cur.fetchone()
    return float(row["calories"]) if row else None


def save_intake(user_id, day, calories):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO daily_intake(user_id, day, calories) VALUES (%s, %s, %s)
                ON CONFLICT(user_id, day) DO UPDATE SET calories=EXCLUDED.calories
            """, (user_id, day.isoformat(), float(calories)))


def get_food_diary_total(user_id, day):
    """Total from the food tracker's food_entries table, or None if that table does not exist."""
    start = datetime.combine(day, datetime.min.time()).isoformat()
    end = (datetime.combine(day, datetime.min.time()) + timedelta(days=1)).isoformat()
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT to_regclass('public.food_entries') AS t")
            if cur.fetchone()["t"] is None:
                return None
            cur.execute("""
                SELECT COALESCE(SUM(calories), 0) AS total FROM food_entries
                WHERE user_id=%s AND entry_date >= %s AND entry_date < %s
            """, (user_id, start, end))
            return float(cur.fetchone()["total"])


def get_history(user_id, days=10):
    start = (today_local() - timedelta(days=days - 1)).isoformat()
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT entry_date AS day, SUM(calories_burned) AS burned
                FROM exercise_entries WHERE user_id=%s AND entry_date >= %s
                GROUP BY entry_date
            """, (user_id, start))
            burned = {r["day"]: float(r["burned"]) for r in cur.fetchall()}
            cur.execute("SELECT day, calories FROM daily_intake WHERE user_id=%s AND day >= %s", (user_id, start))
            consumed = {r["day"]: float(r["calories"]) for r in cur.fetchall()}
    all_days = sorted(set(burned) | set(consumed), reverse=True)
    return [(d, consumed.get(d, 0.0), burned.get(d, 0.0)) for d in all_days]


