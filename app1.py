@contextmanager
def get_connection():
    conn = psycopg2.connect(
        host=st.secrets["postgres"]["host"],
        port=int(st.secrets["postgres"].get("port", 5432)),
        dbname=st.secrets["postgres"].get("database", "postgres"),
        user=st.secrets["postgres"]["user"],
        password=st.secrets["postgres"]["password"],
        sslmode="require",
        connect_timeout=15,
        cursor_factory=RealDictCursor,
    )
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    with get_connection() as conn:
        with conn.cursor() as cur:
            # Shared with the food tracker: safe if these tables already exist.
            cur.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    password_salt TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            cur.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower ON users (LOWER(username))")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS user_settings (
                    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                    daily_target DOUBLE PRECISION NOT NULL DEFAULT 2000
                )
            """)
            # New columns for this app (safe migration)
            cur.execute("ALTER TABLE user_settings ADD COLUMN IF NOT EXISTS maintenance_calories DOUBLE PRECISION NOT NULL DEFAULT 2000")
            cur.execute("ALTER TABLE user_settings ADD COLUMN IF NOT EXISTS body_weight_kg DOUBLE PRECISION NOT NULL DEFAULT 70")
            # New tables for this app
            cur.execute("""
                CREATE TABLE IF NOT EXISTS exercise_entries (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    activity TEXT NOT NULL,
                    minutes DOUBLE PRECISION NOT NULL,
                    calories_burned DOUBLE PRECISION NOT NULL,
                    entry_date TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            cur.execute("CREATE INDEX IF NOT EXISTS idx_exercise_user_date ON exercise_entries(user_id, entry_date)")
            cur.execute("""
                CREATE TABLE IF NOT EXISTS daily_intake (
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    day TEXT NOT NULL,
                    calories DOUBLE PRECISION NOT NULL,
                    PRIMARY KEY (user_id, day)
                )
            """)


