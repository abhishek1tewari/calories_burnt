def hash_password(password, salt=None):
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 310_000)
    return digest.hex(), salt.hex()


def verify_password(password, stored_hash, stored_salt):
    try:
        salt = bytes.fromhex(stored_salt)
        candidate, _ = hash_password(password, salt)
        return hmac.compare_digest(candidate, stored_hash)
    except (ValueError, TypeError):
        return False


def create_user(username, password):
    username = username.strip()
    if len(username) < 3:
        return False, "Username must contain at least 3 characters."
    if len(password) < 8:
        return False, "Password must contain at least 8 characters."
    password_hash, salt = hash_password(password)
    now = datetime.now().isoformat(timespec="seconds")
    try:
        with get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    "INSERT INTO users (username, password_hash, password_salt, created_at) "
                    "VALUES (%s, %s, %s, %s) RETURNING id",
                    (username, password_hash, salt, now),
                )
                user_id = cur.fetchone()["id"]
                cur.execute("INSERT INTO user_settings(user_id) VALUES (%s)", (user_id,))
        return True, "Account created. You are now logged in."
    except errors.UniqueViolation:
        return False, "That username already exists. Please choose another."


def authenticate_user(username, password):
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT * FROM users WHERE LOWER(username)=LOWER(%s)", (username.strip(),))
            user = cur.fetchone()
    if user and verify_password(password, user["password_hash"], user["password_salt"]):
        return {"id": user["id"], "username": user["username"]}
    return None


